// Цвета Google — у каждого вида объекта свой
const COLORS = ['#1a73e8', '#ea4335', '#fbbc04', '#34a853', '#a142f4', '#12b5cb', '#fa7b17', '#f538a0'];

function labelOf(cls) {
    return LABELS[cls] || [cls, '🔹'];
}

function colorOf(cls) {
    let h = 0;
    for (const ch of cls) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
    return COLORS[h % COLORS.length];
}
