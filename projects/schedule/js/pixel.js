// Склеиваем соседние пиксели строки в один прямоугольник — путь получается коротким
function toPath(rows) {
    let d = '';
    rows.forEach((row, y) => {
        let x = 0;
        while (x < row.length) {
            if (row[x] !== '#') { x++; continue; }
            let len = 1;
            while (row[x + len] === '#') len++;
            d += `M${x} ${y}h${len}v1h-${len}z`;
            x += len;
        }
    });
    return d;
}

const cache = {};

// Возвращает HTML-строку <svg> иконки. Размер задаётся в CSS (класс .px-icon)
export function icon(name, extraClass = '') {
    const rows = ICONS[name];
    if (!rows) return '';
    cache[name] ??= toPath(rows);
    const w = rows[0].length, h = rows.length;
    return `<svg class="px-icon ${extraClass}" viewBox="0 0 ${w} ${h}" width="${w * 2}" height="${h * 2}" `
        + `shape-rendering="crispEdges" aria-hidden="true"><path fill="currentColor" d="${cache[name]}"/></svg>`;
}

// Вставляет иконки во все элементы с атрибутом data-icon="имя"
export function fillIcons(root = document) {
    root.querySelectorAll('[data-icon]').forEach(el => {
        el.innerHTML = icon(el.dataset.icon);
    });
}
